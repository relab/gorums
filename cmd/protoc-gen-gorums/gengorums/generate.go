// GenerateVersionMarkers specifies whether to generate version markers.
var GenerateVersionMarkers = true

// GenerateFile generates a _gorums.pb.go file containing Gorums service
// definitions. It returns an error if the file cannot be generated as written.
func GenerateFile(gen *protogen.Plugin, file *protogen.File) error {
	if ok, err := gorumsGuard(gen, file); !ok {
		return err
	}
	filename := file.GeneratedFilenamePrefix + "_gorums.pb.go"
	g := gen.NewGeneratedFile(filename, file.GoImportPath)
	genGeneratedHeader(gen, file, g)
	g.P("package ", file.GoPackageName)
	g.P()
	genVersionCheck(g)
	g.P(staticCode)
	g.P()
	for path, ident := range pkgIdentMap {
		addImport(path, ident, g)
	}
	generateFileContent(file, g)
	return nil
}

func genGeneratedHeader(gen *protogen.Plugin, file *protogen.File, g *protogen.GeneratedFile) {
	g.P("// Code generated by protoc-gen-gorums. DO NOT EDIT.")

	if GenerateVersionMarkers {
		g.P("// versions:")
		protocVersion := "(unknown)"
		if v := gen.Request.GetCompilerVersion(); v != nil {
			protocVersion = fmt.Sprintf("v%v.%v.%v", v.GetMajor(), v.GetMinor(), v.GetPatch())
		}
		g.P("// \tprotoc-gen-gorums ", version.String())
		g.P("// \tprotoc            ", protocVersion)
	}

	if file.Proto.GetOptions().GetDeprecated() {
		g.P("// ", file.Desc.Path(), " is a deprecated file.")
	} else {
		g.P("// source: ", file.Desc.Path())
	}
	g.P()
}

func genVersionCheck(g *protogen.GeneratedFile) {
	if GenerateVersionMarkers {
		gorumsimplPath := protogen.GoImportPath("github.com/relab/gorums/runtime/gorumsimpl")
		enforceVersion := g.QualifiedGoIdent(gorumsimplPath.Ident("EnforceVersion"))
		minVersion := g.QualifiedGoIdent(gorumsimplPath.Ident("MinVersion"))
		maxVersion := g.QualifiedGoIdent(gorumsimplPath.Ident("MaxVersion"))
		g.P("const (")
		g.P("// Verify that this generated code is sufficiently up-to-date.")
		g.P("_ = ", enforceVersion, "(", gorumsimpl.GenVersion, " - ", minVersion, ")")
		g.P("// Verify that the gorums runtime is sufficiently up-to-date.")
		g.P("_ = ", enforceVersion, "(", maxVersion, " - ", gorumsimpl.GenVersion, ")")
		g.P(")")
		g.P()
	}
}

// gorumsGuard reports whether there is something for Gorums to generate for
// the given file. It returns an error, and false, if the file has Gorums
// methods but cannot be generated as written.
func gorumsGuard(gen *protogen.Plugin, file *protogen.File) (bool, error) {
	if len(file.Services) == 0 || !hasGorumsMethods(file.Services) {
		// there is nothing for this plugin to do
		return false, nil
	}
	if len(file.Services) > 1 {
		// To build multiple services, make separate proto files and
		// run the plugin separately for each proto file.
		// These cannot share the same Go package.
		return false, fmt.Errorf("%s: Gorums does not support multiple services in the same proto file", file.Desc.Path())
	}
	if err := checkReservedIdents(gen, file); err != nil {
		return false, err
	}
	for _, method := range file.Services[0].Methods {
		if _, info := callType(method); info != nil {
			if err := validateOptions(method); err != nil {
				return false, err
			}
		}
	}
	return true, nil
}

// checkReservedIdents returns an error if a Gorums reserved identifier names a
// Go declaration in the file's Go package: a message or enum of any file in
// the package, or an RPC method of the file's service. Each would collide with
// the generated type aliases or client functions.
func checkReservedIdents(gen *protogen.Plugin, file *protogen.File) error {
	check := func(kind, name string) error {
		if slices.Contains(reservedIdents, name) {
			return fmt.Errorf("%v.proto: contains %s %s, which is a reserved Gorums identifier", file.GeneratedFilenamePrefix, kind, name)
		}
		return nil
	}
	for _, f := range gen.Files {
		if f.GoImportPath != file.GoImportPath {
			continue
		}
		for _, msg := range f.Messages {
			if err := check("message", msg.GoIdent.GoName); err != nil {
				return err
			}
		}
		for _, enum := range f.Enums {
			if err := check("enum", enum.GoIdent.GoName); err != nil {
				return err
			}
		}
	}
	for _, service := range file.Services {
		for _, method := range service.Methods {
			if err := check("RPC method", method.GoName); err != nil {
				return err
			}
		}
	}
	return nil
}

// generateFileContent generates the Gorums service definitions, excluding the package statement.
func generateFileContent(file *protogen.File, g *protogen.GeneratedFile) {
	// 1. Data Types (Async/Correctable aliases)
	genGorumsType(g, file.Services, "types")

	// 2. Reference Imports
	genReferenceImports(g, file.Services)

	// 3. Client Methods (in proto order)
	genGorumsMethods(g, file.Services, "")

	// 4. Server Interface and Registration
	genGorumsType(g, file.Services, "server")
}

// genReferenceImports generates a dummy reference to suppress unused import errors.
// These are only needed for oneway calls (unicast/multicast) because their
// output type is qualified by the commonVariables template but may be unused.
func genReferenceImports(g *protogen.GeneratedFile, services []*protogen.Service) {
	seen := make(map[string]bool)
	var idents []string
	for _, service := range services {
		for _, method := range service.Methods {
			if !hasMethodOption(method, gorums.E_Multicast, gorums.E_Unicast) {
				continue
			}
			qualified := g.QualifiedGoIdent(method.Output.GoIdent)
			if !strings.Contains(qualified, ".") {
				continue
			}
			pkg := qualified[:strings.LastIndex(qualified, ".")]
			if seen[pkg] {
				continue
			}
			seen[pkg] = true
			idents = append(idents, qualified)
		}
	}
	if len(idents) > 0 {
		g.P("// Reference imports to suppress errors if they are not otherwise used.")
		for _, ident := range idents {
			g.P("var _ ", ident)
		}
		g.P()
	}
}

// genGorumsType generates Gorums methods and corresponding data structures for the given call type.
func genGorumsType(g *protogen.GeneratedFile, services []*protogen.Service, callType string) {
	if callTypeInfo := gorumsCallTypesInfo[callType]; callTypeInfo.extInfo == nil {
		// servicesData hold the services to generate and a reference to the file in which
		// the services should be generated. This is data to be used by template generator.
		type servicesData struct {
			GenFile  *protogen.GeneratedFile
			Services []*protogen.Service
		}
		g.P(mustExecute(parseTemplate(callType, callTypeInfo.template), servicesData{g, services}))
	}
}

// genGorumsMethods generates Gorums methods for the given call type.
func genGorumsMethods(g *protogen.GeneratedFile, services []*protogen.Service, callType string) {
	for _, service := range services {
		for _, method := range service.Methods {
			genMethod(g, method, callType)
		}
	}
}

// genMethod generates the Gorums method for the given method and call type.
func genMethod(g *protogen.GeneratedFile, method *protogen.Method, targetType string) {
	typeName, info := callType(method)
	if info == nil {
		return
	}
	if targetType != "" && targetType != typeName {
		return
	}
	type methodData struct {
		GenFile *protogen.GeneratedFile
		Method  *protogen.Method
	}
	g.P(mustExecute(parseTemplate(typeName, info.template), methodData{g, method}))
}

// callType returns call type information for the given method.
// If the given method has specified a Gorums method option that
// correspond to a call type, this call type is returned. Further,
// if the call type has a sub call type, then this is returned instead.
func callType(method *protogen.Method) (string, *callTypeInfo) {
	for name, callTypeInfo := range gorumsCallTypesInfo {
		if callType := callTypeInfo.deriveCallType(method); callType.check(method) {
			return name, callType
		}
	}
	return "", nil
}

// hasGorumsMethods returns true if one of the methods in the set of services
// has a Gorums call type.
func hasGorumsMethods(services []*protogen.Service) bool {
	for _, service := range services {
		for _, method := range service.Methods {
			if _, callType := callType(method); callType != nil {
				return true
			}
		}
	}
	return false
}

// callTypeInfo holds the extension for an option type, the template used to
// generate a method annotated with the option, and a chkFn function that
// returns true if code for the option type should be generated for the given
// method.
type callTypeInfo struct {
	extInfo        *protoimpl.ExtensionInfo
	template       string
	chkFn          func(m *protogen.Method) bool
	nestedCallType map[string]*callTypeInfo
}

// check returns true if the given method is associated with this call type.
func (c *callTypeInfo) check(m *protogen.Method) bool {
	if c != nil && c.chkFn != nil {
		return c.chkFn(m)
	}
	return false
}

// deriveCallType resolves the nested call type if any.
func (c *callTypeInfo) deriveCallType(m *protogen.Method) *callTypeInfo {
	if c != nil {
		for _, nestedCallType := range c.nestedCallType {
			if nestedCallType.chkFn(m) {
				return nestedCallType
			}
		}
	}
	return c
}

// callTypeName returns the name of the call type option with the prefix removed.
func callTypeName(ext *protoimpl.ExtensionInfo) string {
	s := string(ext.TypeDescriptor().FullName())
	return s[strings.LastIndex(s, ".")+1:]
}

// gorumsCallTypesInfo maps Gorums call type names to callTypeInfo.
// This includes details such as the template, extension info and
// a chkFn function used to check for the particular call type.
// The entries in this map is used to generate dev/zorums_{type}.pb.go
// files for the different keys.
var gorumsCallTypesInfo = map[string]*callTypeInfo{
	"types":  {template: dataTypes},
	"server": {template: server},

	callTypeName(gorums.E_Remotecall): {
		extInfo:  gorums.E_Remotecall,
		template: remoteCall,
		chkFn: func(m *protogen.Method) bool {
			return !hasMethodOption(m, gorumsCallTypes...)
		},
	},
	callTypeName(gorums.E_Quorumcall): {
		extInfo: gorums.E_Quorumcall,
		chkFn: func(m *protogen.Method) bool {
			return hasMethodOption(m, gorums.E_Quorumcall)
		},
		nestedCallType: map[string]*callTypeInfo{
			"quorumcall": {
				extInfo:  gorums.E_Quorumcall,
				template: quorumCall,
				chkFn: func(m *protogen.Method) bool {
					return hasMethodOption(m, gorums.E_Quorumcall) && !m.Desc.IsStreamingServer()
				},
			},
			"quorumcall_stream": {
				extInfo:  gorums.E_Quorumcall,
				template: quorumCallStream,
				chkFn: func(m *protogen.Method) bool {
					return hasMethodOption(m, gorums.E_Quorumcall) && m.Desc.IsStreamingServer()
				},
			},
		},
	},
	callTypeName(gorums.E_Multicast): {
		extInfo:  gorums.E_Multicast,
		template: multicastCall,
		chkFn: func(m *protogen.Method) bool {
			return hasMethodOption(m, gorums.E_Multicast)
		},
	},
	callTypeName(gorums.E_Unicast): {
		extInfo:  gorums.E_Unicast,
		template: unicastCall,
		chkFn: func(m *protogen.Method) bool {
			return hasMethodOption(m, gorums.E_Unicast)
		},
	},
}

// gorumsCallTypes should list all available call types supported by Gorums.
// These are considered mutually incompatible.
var gorumsCallTypes = []*protoimpl.ExtensionInfo{
	gorums.E_Quorumcall,
	gorums.E_Multicast,
	gorums.E_Unicast,
}

// hasMethodOption returns true if the method has one of the given method options.
func hasMethodOption(method *protogen.Method, methodOptions ...*protoimpl.ExtensionInfo) bool {
	ext := protoimpl.X.MessageOf(method.Desc.Options()).Interface()
	for _, callType := range methodOptions {
		if proto.HasExtension(ext, callType) {
			return true
		}
	}
	return false
}

// validateOptions returns an error if the extension options
// for the provided method are incompatible.
func validateOptions(method *protogen.Method) error {
	switch {
	case !hasMethodOption(method, gorums.E_Multicast) && method.Desc.IsStreamingClient():
		return optionErrorf("is required for client-server stream methods", method, gorums.E_Multicast)

	case !hasMethodOption(method, gorums.E_Quorumcall) && method.Desc.IsStreamingServer():
		return optionErrorf("is required for server-client stream methods", method, gorums.E_Quorumcall)
	}
	return nil
}

func optionErrorf(s string, method *protogen.Method, ext *protoimpl.ExtensionInfo) error {
	return fmt.Errorf("%s.%s: option '%s' "+s, method.Parent.Desc.Name(), method.Desc.Name(), ext.TypeDescriptor().FullName())
}
