#!/usr/bin/env bash
# Runs the sweep smoke test on a throwaway Docker cluster and verifies it.
#
# It starts a driver container (smoke-driver) and SMOKE_N peer containers
# (smoke-1 ... smoke-N, default 5), launches a detached -test sweep of
# SymmetricQuorumCall and SymmetricMulticast in both stream modes, waits for it,
# collects it, and runs sweep -verify. The exit status is the verdict. The run
# directory is $SMOKE_OUT/smoke-docker and the verdict is $SMOKE_OUT/verdict.md
# (default SMOKE_OUT: benchkit/out/smoke-docker). The cluster is removed on exit.
#
# Only the driver's sshd is published, on 127.0.0.1:${SMOKE_SSH_PORT:-2222};
# the driver reaches the peers by container name through Docker's DNS.
#
# Only one run per machine is allowed, because the cleanup removes every smoke
# container on the Docker daemon. A second run fails at once while the lock
# directory ${TMPDIR:-/tmp}/gorums-smoke-docker.lock names a live process; a
# lock left by a process that is gone is taken over.
#
# Sweep builds for the Docker host's architecture (GOARCH=$(go env GOARCH)), so
# the containers run natively on arm64 and amd64 hosts. Extra -verify flags,
# such as -max-drift 5ms, can be passed in SMOKE_VERIFY_ARGS.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../../.." && pwd)
n=${SMOKE_N:-5}
port=${SMOKE_SSH_PORT:-2222}
out=${SMOKE_OUT:-$root/benchkit/out/smoke-docker}
label=smoke-docker
network=gorums-smoke
image=gorums-smoke

# cluster_down removes every container named smoke-* on the smoke network, and
# then the network. It is safe to run when nothing is up.
cluster_down() {
    local ids
    ids=$(docker ps --all --quiet --filter "network=$network" --filter name=smoke-)
    if [[ -n $ids ]]; then
        # shellcheck disable=SC2086 # one argument per container id
        docker rm --force $ids > /dev/null
    fi
    docker network rm "$network" > /dev/null 2>&1 || true
}

# start_container starts the container name from the smoke image, with any
# extra docker run flags.
start_container() {
    local name=$1
    shift
    docker run --detach --name "$name" --hostname "$name" --network "$network" \
        --ulimit nofile=65536:65536 "$@" "$image" > /dev/null
}

# cluster_up writes a throwaway key pair and an SSH config for smoke-driver
# into dir, builds the image with the public key installed, and starts the
# driver and n peers. It returns when the driver's sshd accepts the key.
cluster_up() {
    local n=$1 dir=$2
    ssh-keygen -q -t ed25519 -N '' -C gorums-smoke -f "$dir/id_ed25519"
    cat > "$dir/ssh_config" <<EOF
# Generated by benchkit/smoke/docker/run.sh for the Docker smoke cluster.
Host smoke-driver
    HostName 127.0.0.1
    Port $port
    User smoke
    IdentityFile $dir/id_ed25519
    IdentitiesOnly yes
    ForwardAgent yes
    StrictHostKeyChecking no
    UserKnownHostsFile /dev/null
    LogLevel ERROR
EOF

    docker build --quiet --tag "$image" \
        --build-arg SMOKE_PUBKEY="$(cat "$dir/id_ed25519.pub")" "$here" > /dev/null
    docker network create "$network" > /dev/null

    start_container smoke-driver --publish "127.0.0.1:$port:22"
    local i
    for ((i = 1; i <= n; i++)); do
        start_container "smoke-$i"
    done

    local tries=0
    until ssh -F "$dir/ssh_config" -o BatchMode=yes -o ConnectTimeout=2 smoke-driver true 2> /dev/null; do
        if ((++tries >= 30)); then
            echo "run.sh: the driver's sshd did not come up" >&2
            return 1
        fi
        sleep 1
    done
    echo "smoke cluster up: smoke-driver + smoke-[1-$n]"
}

# Take the lock before any cleanup, so this run never removes the cluster of a
# run that holds it.
lock=${TMPDIR:-/tmp}/gorums-smoke-docker.lock
if ! mkdir "$lock" 2> /dev/null; then
    holder=$(cat "$lock/pid" 2> /dev/null || true)
    if [[ -n $holder ]] && kill -0 "$holder" 2> /dev/null; then
        echo "run.sh: another smoke run (pid $holder) is using the Docker daemon; try again when it is done" >&2
        exit 1
    fi
    rm -rf "$lock"
    mkdir "$lock"
fi
echo "$$" > "$lock/pid"

# Remove the previous verdict before any step that can fail, so a failed run
# never leaves an earlier PASS at the verdict path.
mkdir -p "$out"
rm -rf "${out:?}/$label" "${out:?}/.sweep-last.json" "${out:?}/verdict.md"

tmp=$(mktemp -d)
# The SSH config names files in tmp, and rsync passes it to ssh -F, which
# cannot handle a path with spaces.
if [[ $tmp == *" "* ]]; then
    echo "run.sh: the temporary directory must not contain spaces: $tmp" >&2
    rm -rf "$tmp" "$lock"
    exit 2
fi
# own_agent is the ssh-agent this script starts; cleanup stops only that one,
# never an agent inherited from the caller's environment.
own_agent=
cleanup() {
    local status=$?
    cluster_down
    if [[ -n $own_agent ]]; then
        kill "$own_agent" 2> /dev/null || true
    fi
    rm -rf "$tmp" "$lock"
    exit "$status"
}
trap cleanup EXIT INT TERM

cluster_down
cluster_up "$n" "$tmp"

eval "$(ssh-agent -s)" > /dev/null
own_agent=$SSH_AGENT_PID
ssh-add -q "$tmp/id_ed25519"

just --justfile "$root/Justfile" sweep

export GOARCH="${GOARCH:-$(go env GOARCH)}"
cd "$root/benchkit"
sweep=./cmd/sweep/sweep
run_flags=(-test "$n" -sweep "$label" -stream-mode "dual,dedup" -benchmarks "SymmetricQuorumCall,SymmetricMulticast")

"$sweep" -config "$tmp/ssh_config" -outdir "$out" "${run_flags[@]}" -hosts "smoke-[1-$n]" -detach smoke-driver
"$sweep" -config "$tmp/ssh_config" -outdir "$out" -collect -wait -wait-timeout 5m
# shellcheck disable=SC2086 # SMOKE_VERIFY_ARGS holds separate flags
"$sweep" -verify "$out/$label" "${run_flags[@]}" ${SMOKE_VERIFY_ARGS:-} -summary "$out/verdict.md"
