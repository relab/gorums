// run executes one subcommand and returns the process exit code.
func run(args []string, in io.Reader, stdout, stderr io.Writer) int {
	if len(args) == 0 {
		fmt.Fprint(stderr, usage)
		return 2
	}
	name := args[0]
	switch name {
	case "-h", "-help", "--help", "help":
		fmt.Fprint(stdout, usage)
		return 0
	case "prepare", "pr", "publish", "check-branch", "cluster-key":
	default:
		fmt.Fprintf(stderr, "%s: unknown command %q\n\n%s", progName, name, usage)
		return 2
	}
	fs := flag.NewFlagSet(progName+" "+name, flag.ContinueOnError)
	fs.SetOutput(stderr)
	fs.Usage = func() {
		fmt.Fprintf(stderr, "Usage: %s %s [flags]\n\n%s\nFlags:\n", progName, name, descriptions[name])
		fs.PrintDefaults()
	}
	dryRun := fs.Bool("dry-run", false, "show what would be done and change nothing: lines that start with + are skipped, lines that start with ? are read-only and run")
	var do func(*tool) error
	switch name {
	case "prepare":
		var o prepareOptions
		fs.StringVar(&o.version, "version", "", "release `version`, such as v0.12.0 or v0.12.0-rc.1 (default: the version gorelease suggests)")
		fs.BoolVar(&o.allowMajor, "allow-major", false, "confirm a major version bump, such as v0 to v1")
		fs.BoolVar(&o.bumpGen, "bump-gen", false, "set GenVersion to the new minor version: newly generated code needs this release's runtime")
		fs.BoolVar(&o.bumpMin, "bump-min", false, "set MinVersion and GenVersion to the new minor version: code generated by older releases stops compiling")
		fs.BoolVar(&o.skipUpgrade, "skip-upgrade", false, "do not upgrade dependencies")
		fs.BoolVar(&o.skipTests, "skip-tests", false, "do not run just test and just testrace")
		do = func(t *tool) error { return t.prepare(o) }
	case "pr":
		var o prOptions
		fs.BoolVar(&o.web, "web", false, "open the pull request in the browser")
		do = func(t *tool) error { return t.pr(o) }
	case "publish":
		var o publishOptions
		fs.BoolVar(&o.yes, "yes", false, "merge the pull request without asking")
		fs.BoolVar(&o.draft, "draft", false, "create the GitHub release as a draft")
		do = func(t *tool) error { return t.publish(o) }
	case "check-branch":
		var o checkBranchOptions
		fs.StringVar(&o.branch, "branch", "", "the `branch` to check, such as release/v0.12.0 (default: the checked-out branch)")
		do = func(t *tool) error { return t.checkBranch(o) }
	case "cluster-key":
		var o clusterKeyOptions
		fs.BoolVar(&o.prune, "prune", false, "remove all but the newest release smoke key, after cluster-check passed with it")
		fs.StringVar(&o.jump, "jump", "gorums@ssh4.ux.uis.no", "the ssh `destination` of the account gorums on the jump host")
		fs.StringVar(&o.cluster, "cluster", "gorums@bb1", "the ssh `destination` of the account gorums on the cluster, as your SSH config resolves it")
		do = func(t *tool) error { return t.clusterKey(o) }
	}
	if err := fs.Parse(args[1:]); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			return 0
		}
		return 2
	}
	if fs.NArg() > 0 {
		fmt.Fprintf(stderr, "%s %s: unexpected argument %q\n", progName, name, fs.Arg(0))
		return 2
	}
	root, err := repoRoot()
	if err != nil {
		fmt.Fprintf(stderr, "%s: %v\n", progName, err)
		return 1
	}
	t := &tool{
		root:          root,
		dryRun:        *dryRun,
		run:           execRunner{root: root, stdout: stdout, stderr: stderr},
		out:           stdout,
		in:            in,
		isTerminal:    isTerminal(in),
		sleep:         time.Sleep,
		lookPath:      exec.LookPath,
		path:          os.Getenv("PATH"),
		now:           time.Now,
		verifyTimeout: defaultVerifyTimeout,
	}
	if err := do(t); err != nil {
		fmt.Fprintf(stderr, "%s %s: %v\n", progName, name, err)
		return 1
	}
	return 0
}

// repoRoot returns the top-level directory of the enclosing git repository.
func repoRoot() (string, error) {
	out, err := exec.Command("git", "rev-parse", "--show-toplevel").Output()
	if err != nil {
		return "", fmt.Errorf("not inside a git repository: %w", err)
	}
	return strings.TrimSpace(string(out)), nil
}

// isTerminal reports whether r is an interactive terminal.
func isTerminal(r io.Reader) bool {
	f, ok := r.(*os.File)
	if !ok {
		return false
	}
	st, err := f.Stat()
	return err == nil && st.Mode()&os.ModeCharDevice != 0
}
